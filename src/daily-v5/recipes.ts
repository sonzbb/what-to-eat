const EGG_DISH_PATTERN = /炒蛋|蒸蛋|水蛋|滑蛋|蛋黄|窝蛋|餐蛋|蛋炒|鸡蛋|咸蛋|皮蛋|瑶柱蒸蛋/;
const STAPLE_DISH_PATTERN = /炒饭|煲仔饭|炒米|炒面|云吞面|牛腩面|公仔面|粥|萝卜糕|马蹄糕/;

function groupFromText(text: string): MainGroup | null {
  if (/鸡蛋|咸蛋|皮蛋|蛋黄/.test(text)) return "蛋类";
  if (/鸡|凤爪/.test(text)) return "鸡禽";
  if (/鸭|鹅/.test(text)) return "鸭鹅";
  if (/猪|排骨|肋排|肉饼|五花肉|猪手|猪肚|猪肝|猪肺|猪骨|瘦肉|叉烧|烧肉|腊肉|腊肠|生肠/.test(text)) {
    return "猪肉";
  }
  if (/牛/.test(text)) return "牛肉";
  if (/羊/.test(text)) return "羊肉";
  if (/虾|蟹|鱿|蚝|扇贝|鲍|花甲|蚬|蛏|带子|海鲜|濑尿虾|鱼肚/.test(text)) return "虾蟹贝";
  if (/鱼|鲈|鲩|鲮|鲫|鲳|黄花|塘鲺|马鲛/.test(text)) return "鱼类";
  if (/豆腐|豆卜|腐竹|枝竹|支竹|豆干/.test(text)) return "豆制品";
  if (/米饭|大米|河粉|米粉|面|粥|粘米粉/.test(text)) return "米面粥点";
  if (/菜|瓜|茄|芹|芥兰|生菜|通菜|荷兰豆|莲藕|土豆|青椒|萝卜|花菜|四季豆|苋菜|西兰花/.test(text)) {
    return "蔬菜";
  }
  return null;
}

function inferMainGroup(name: string, main: string): MainGroup {
  if (EGG_DISH_PATTERN.test(name)) return "蛋类";
  if (STAPLE_DISH_PATTERN.test(name)) return "米面粥点";
  return groupFromText(main) ?? groupFromText(name) ?? "其他";
}

